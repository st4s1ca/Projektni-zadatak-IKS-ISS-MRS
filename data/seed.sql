CREATE TABLE "Korisnik" (
    "id" VARCHAR(36) PRIMARY KEY,
    "korisnickoIme" VARCHAR(60) NOT NULL UNIQUE,
    "email" VARCHAR(255) NOT NULL UNIQUE,
    "lozinka" VARCHAR(255) NOT NULL,
    "admin" BOOLEAN NOT NULL DEFAULT FALSE,
    "aktiviranNalog" BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE "Profil" (
    "korisnikId" VARCHAR(36) PRIMARY KEY REFERENCES "Korisnik"("id") ON DELETE CASCADE,
    "fotografija" TEXT,
    "region" VARCHAR(100),
    "biografija" TEXT,
    "brojObjavljenihRecepata" INTEGER NOT NULL DEFAULT 0 CHECK ("brojObjavljenihRecepata" >= 0)
);

CREATE TABLE "KategorijaNamirnice" (
    "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "naziv" VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE "Namirnica" (
    "id" VARCHAR(36) PRIMARY KEY,
    "naziv" VARCHAR(150) NOT NULL,
    "kategorija" INTEGER NOT NULL REFERENCES "KategorijaNamirnice"("id"),
    "tip" VARCHAR(20) NOT NULL CHECK ("tip" IN ('GENERICKA', 'BRENDIRANA')),
    "jedinicaMere" VARCHAR(30) NOT NULL CHECK ("jedinicaMere" IN ('GRAM', 'KILOGRAM', 'CUPS'))
);

CREATE TABLE "Recept" (
    "id" VARCHAR(36) PRIMARY KEY,
    "naziv" VARCHAR(200) NOT NULL,
    "brojPorcija" INTEGER NOT NULL CHECK ("brojPorcija" > 0),
    "trajanjePripremeMinuti" INTEGER NOT NULL CHECK ("trajanjePripremeMinuti" >= 0),
    "regionAutora" VARCHAR(100),
    "autorId" VARCHAR(36) NOT NULL REFERENCES "Korisnik"("id")
);

CREATE TABLE "SastojakRecepta" (
    "receptId" VARCHAR(36) NOT NULL REFERENCES "Recept"("id") ON DELETE CASCADE,
    "namirnicaId" VARCHAR(36) NOT NULL REFERENCES "Namirnica"("id"),
    "kolicina" NUMERIC(10,2) CHECK ("kolicina" IS NULL OR "kolicina" > 0),
    "jedinica" VARCHAR(30) NOT NULL CHECK ("jedinica" IN ('GRAM', 'KILOGRAM', 'CUPS')),
    PRIMARY KEY ("receptId", "namirnicaId")
);

CREATE TABLE "KorakPripreme" (
    "id" VARCHAR(36) PRIMARY KEY,
    "redniBroj" INTEGER NOT NULL CHECK ("redniBroj" > 0),
    "naslov" VARCHAR(150) NOT NULL,
    "tekst" TEXT NOT NULL,
    "trajanje" INTEGER CHECK ("trajanje" IS NULL OR "trajanje" > 0),
    "tipPripreme" VARCHAR(40) NOT NULL CHECK (
        "tipPripreme" IN (
            'KUVANJE', 'PECENJE', 'PRZENJE', 'DINSTANJE', 'GRILOVANJE',
            'POHOVANJE', 'KUVANJE NA PARI', 'BEZ TERMICKE OBRADE', 'OSTALO'
        )
    ),
    "receptId" VARCHAR(36) NOT NULL REFERENCES "Recept"("id") ON DELETE CASCADE,
    UNIQUE ("receptId", "redniBroj"),
    CHECK ("tipPripreme" IN ('BEZ TERMICKE OBRADE', 'OSTALO') OR "trajanje" IS NOT NULL)
);

